// 곡선 점 (u,v 평면) — 원호
function arcPts(cu, cv, r, a0, a1, n = 6) { const o = []; for (let i = 0; i <= n; i++) { const a = a0 + (a1 - a0) * i / n; o.push(cu + Math.cos(a) * r, cv + Math.sin(a) * r); } return o; }
// 휘어진 탄창 윤곽: 위(0,0)에서 아래로 길이 L, 폭 w, 앞으로 휘는 정도 bend(라디안)
function curveMagPts(L, w, bend, fwd = 0) {
  const n = 8, F = [], Bk = []; let cu = fwd, cv = 0;
  for (let i = 0; i <= n; i++) {
    const s = i / n, a = bend * s;
    if (i > 0) { const a0 = bend * (i - 1) / n, ds = L / n; cu += Math.sin((a + a0) / 2) * ds; cv -= Math.cos((a + a0) / 2) * ds; }
    const pu = Math.cos(a) * w / 2, pv = Math.sin(a) * w / 2;
    F.push([cu + pu, cv + pv]); Bk.push([cu - pu, cv - pv]);
  }
  const o = []; for (const p of F) o.push(p[0], p[1]); for (let i = Bk.length - 1; i >= 0; i--) o.push(Bk[i][0], Bk[i][1]);
  return o;
}

// 만들기 도구 (부모 그룹에 붙여요)
function gk(parent) {
  const K = { g: parent };
  const add = (m, x = 0) => { m.position.x += x; m.castShadow = true; parent.add(m); return m; };
  const shape = (pts) => { const s = new THREE.Shape(); s.moveTo(pts[0], pts[1]); for (let i = 2; i < pts.length; i += 2) s.lineTo(pts[i], pts[i + 1]); return s; };
  K.P = (pts, w, mat, x = 0, holes) => { // 옆모습 윤곽을 두께 w로
    const s = shape(pts);
    if (holes) for (const h of holes) { const p = new THREE.Path(); p.moveTo(h[0], h[1]); for (let i = 2; i < h.length; i += 2) p.lineTo(h[i], h[i + 1]); s.holes.push(p); }
    const b = Math.min(0.0016, w * 0.18);
    const geo = new THREE.ExtrudeGeometry(s, { depth: Math.max(0.0005, w - 2 * b), bevelEnabled: true, bevelThickness: b, bevelSize: b * 0.8, bevelSegments: 1, curveSegments: 4 });
    geo.translate(0, 0, -Math.max(0.0005, w - 2 * b) / 2); geo.rotateY(Math.PI / 2);
    return add(new THREE.Mesh(geo, mat), x);
  };
  K.B = (u0, u1, v0, v1, w, mat, x = 0) => { const m = new THREE.Mesh(BX(w, Math.abs(v1 - v0), Math.abs(u1 - u0)), mat); m.position.set(0, (v0 + v1) / 2, -(u0 + u1) / 2); return add(m, x); };
  K.C = (u0, u1, v, rb, rf, mat, seg = 12, x = 0, open = false) => { const m = new THREE.Mesh(CY(rb, rf, u1 - u0, seg, open), mat); m.rotation.x = Math.PI / 2; m.position.set(0, v, -(u0 + u1) / 2); return add(m, x); };
  K.X = (u, v, r, len, mat, seg = 14, x = 0) => { const m = new THREE.Mesh(CY(r, r, len, seg), mat); m.rotation.z = Math.PI / 2; m.position.set(0, v, -u); return add(m, x); };
  K.Y = (u, v0, v1, rb, rt, mat, x = 0, seg = 10) => { const m = new THREE.Mesh(CY(rt, rb, v1 - v0, seg), mat); m.position.set(0, (v0 + v1) / 2, -u); return add(m, x); };
  K.ring = (u, v, r, t, mat, x = 0) => { const m = new THREE.Mesh(new THREE.TorusGeometry(r, t, 6, 16), mat); m.position.set(0, v, -u); return add(m, x); };
  K.loop = (u, v, r, t, mat, x = 0, arc = Math.PI * 2, rot = 0) => { const m = new THREE.Mesh(new THREE.TorusGeometry(r, t, 6, 18, arc), mat); m.rotation.set(0, Math.PI / 2, 0); m.rotateZ(rot); m.position.set(0, v, -u); return add(m, x); };
  K.S = (u, v, r, mat, x = 0) => { const m = new THREE.Mesh(new THREE.SphereGeometry(r, 10, 8), mat); m.position.set(0, v, -u); return add(m, x); };
  K.sub = (u, v, x = 0) => { const gg = new THREE.Group(); gg.position.set(x, v, -u); parent.add(gg); return gk(gg); };
  K.rail = (u0, u1, v, w = 0.021, mat = GUNMAT.black) => { // 피카티니 레일 (윗면 = v)
    K.B(u0, u1, v - 0.009, v - 0.003, w, mat);
    for (let u = u0 + 0.004; u < u1 - 0.004; u += 0.01) K.B(u, u + 0.0052, v - 0.004, v, w, mat);
  };
  K.railB = (u0, u1, v, w = 0.021, mat = GUNMAT.black) => { // 아래쪽 레일 (아랫면 = v)
    K.B(u0, u1, v + 0.003, v + 0.009, w, mat);
    for (let u = u0 + 0.004; u < u1 - 0.004; u += 0.01) K.B(u, u + 0.0052, v, v + 0.004, w, mat);
  };
  K.railS = (u0, u1, v, x, mat = GUNMAT.black) => { // 옆 레일
    const s = Math.sign(x); K.B(u0, u1, v - 0.01, v + 0.01, 0.006, mat, x - s * 0.002);
    for (let u = u0 + 0.004; u < u1 - 0.004; u += 0.01) K.B(u, u + 0.0052, v - 0.0095, v + 0.0095, 0.004, mat, x + s * 0.0025);
  };
  // 손잡이 (권총 손잡이): kind별 모양, du/dv로 옮기기
  K.pgrip = (mat, kind = 'ar', du = 0, dv = 0, w = 0.03) => {
    const P = {
      ar: [-0.004, 0.0, -0.02, -0.03, -0.024, -0.05, -0.022, -0.062, -0.03, -0.072, -0.034, -0.1, -0.044, -0.116, -0.078, -0.11, -0.074, -0.08, -0.06, -0.035, -0.052, 0.0],
      ak: [-0.006, 0.0, -0.026, -0.06, -0.04, -0.112, -0.07, -0.108, -0.06, -0.06, -0.046, 0.0],
      hk: [-0.004, 0.0, -0.018, -0.045, -0.03, -0.11, -0.04, -0.12, -0.076, -0.114, -0.07, -0.07, -0.058, -0.03, -0.05, 0.0],
      straight: [0.0, 0.0, -0.012, -0.06, -0.022, -0.11, -0.06, -0.11, -0.05, -0.06, -0.042, 0.0],
      revolver: [0.0, 0.0, -0.028, -0.06, -0.036, -0.1, -0.06, -0.106, -0.066, -0.07, -0.05, -0.02, -0.03, 0.006],
    }[kind];
    const pts = []; for (let i = 0; i < P.length; i += 2) pts.push(P[i] + du, P[i + 1] + dv);
    return K.P(pts, w, mat);
  };
  K.guard = (mat, u0 = -0.016, u1 = 0.03, v = -0.004, depth = 0.034) => { // 방아쇠울 + 방아쇠
    K.P([u1, v, u1 + 0.002, v - depth + 0.008, u1 - 0.01, v - depth, u0, v - depth, u0 - 0.004, v - depth + 0.012, u0, v],
      0.012, mat, 0, [[u1 - 0.005, v - 0.003, u1 - 0.004, v - depth + 0.009, u1 - 0.012, v - depth + 0.005, u0 + 0.004, v - depth + 0.005, u0 + 0.003, v - 0.003]]);
    K.P([0.004, v, 0.007, v - 0.014, 0.002, v - 0.026, -0.002, v - 0.025, 0.001, v - 0.014, -0.002, v], 0.006, GUNMAT.steel);
  };
  return K;
}

// 한 재질끼리 메시를 하나로 합치기 (그리기 횟수 줄이기)
function mergeGun(g) {
  const by = new Map();
  for (const m of g.children) if (m.isMesh && !m.userData.keep) { if (!by.has(m.material)) by.set(m.material, []); by.get(m.material).push(m); }
  for (const [mat, list] of by) {
    if (list.length < 2) continue;
    let n = 0; const geos = list.map(m => { m.updateMatrix(); const geo = m.geometry.index ? m.geometry.toNonIndexed() : m.geometry.clone(); geo.applyMatrix4(m.matrix); n += geo.attributes.position.count; return geo; });
    const pos = new Float32Array(n * 3), nor = new Float32Array(n * 3); let o = 0;
    for (const geo of geos) { pos.set(geo.attributes.position.array, o * 3); nor.set(geo.attributes.normal.array, o * 3); o += geo.attributes.position.count; geo.dispose(); }
    const mg = new THREE.BufferGeometry(); mg.setAttribute('position', new THREE.BufferAttribute(pos, 3)); mg.setAttribute('normal', new THREE.BufferAttribute(nor, 3));
    mg.computeBoundingSphere(); mg.computeBoundingBox();
    const mesh = new THREE.Mesh(mg, mat); mesh.castShadow = true; g.add(mesh);
    for (const m of list) { g.remove(m); m.geometry.dispose(); }
  }
}

